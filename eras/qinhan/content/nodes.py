TAICHU = -104
NODES = []


def t_of(y, m):
    if m is None:
        m = 9 if y < TAICHU else 12
    if y <= TAICHU and m >= 10:
        y -= 1
    return y * 12 + m - 1


def Qg(spec):
    """「政权:郡 郡；政权:郡」→ groups（单位 = 政权）"""
    out = []
    for part in spec.split("；"):
        part = part.strip()
        if not part:
            continue
        k, js = part.split("：")
        u, _, p = k.partition("/")
        out.append((u, p or u, [j if j.endswith(("郡", "史")) else j + "郡" for j in js.split()]))
    return out


def node(key, y, m=None, sys_="X", cent="汉", groups=(), pred=None, ext=None, polmap=None, lab=None, lab_en=None,
         seat=None, h=(), junction=None):
    tx = TEXT[key]
    NODES.append(dict(key=key, t=t_of(y, m), tp="m" if m else "y", label=f"{y}" + (f"·{m}" if m else ""),
                      sys=sys_, cent=cent, groups=list(groups), pred=pred, ext=ext or {}, polmap=polmap or {},
                      lab=lab or {}, lab_en=lab_en or {}, seat=seat or {}, h=list(h), junction=junction,
                      era=tx["era"], era_en=tx["era_en"], title=tx["t"], title_en=tx["te"], desc=tx["d"], desc_en=tx["de"],
                      short=tx["sh"], short_en=tx["she"], era2=tx.get("era2"), era2_en=tx.get("era2_en")))


