# 东汉郡国的英文名（汉末卷 seeds 的 jne 之外，本卷改用的写法）
EN_KIND = {"郡": "Commandery", "国": "Kingdom", "尹": "", "翊": "", "风": ""}


def en_unit(n, pinyin):
    """郡国名 → 英文：南阳郡 Nanyang Commandery，梁国 Kingdom of Liang，京兆尹 Jingzhao Yin"""
    if n in ("京兆尹", "河南尹"):
        return pinyin(n[:-1]) + " Yin"
    if n == "韩国":
        return "Kingdom of Han (韓)"
    if n in ("左冯翊", "右扶风", "内史"):
        return {"左冯翊": "Zuo Pingyi", "右扶风": "You Fufeng", "内史": "Neishi (Capital Region)"}[n]
    if n.endswith("属国"):
        return pinyin(n[:-2]) + " Dependent State"
    if n.endswith("国"):
        return "Kingdom of " + pinyin(n[:-1])
    if n.endswith("郡"):
        return pinyin(n[:-1]) + " Commandery"
    return pinyin(n)
