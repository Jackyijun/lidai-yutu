TS_UNIT = {'环王': '林邑', '文单': '真腊'}           # 唐宋卷的单位键 → 本卷的单位键


def put(d, unit, keys):
    """d 里把 keys 从别的单位挪到 unit"""
    for u in d: d[u] = [k for k in d[u] if k not in keys]
    d.setdefault(unit, []).extend(keys)
    return d


def replay():
    """到目前为止各点的归属（同 src/compile_data.py 的推法）"""
    own = {}
    for n in NODES:
        for a, b in n['move'].items():
            own = {k: (b if v == a else v) for k, v in own.items()}
        for uk, lst in n['own'].items():
            for sid in expand(lst): own[sid] = uk
        for sid in expand(n['drop']): own[sid] = None
    return own


def split_tang():
    """天宝十节度与采访使道：此刻属唐的点，照唐宋卷 755 年节点分到各节度、道；唐宋卷没有的点取最近一个有的点的"""
    import math
    own, SE = replay(), {s['id']: s for s in SEEDS}
    where = {k: u for u in TANG_DH for k in TS755[u]}
    out = {}
    for k, u in own.items():
        if u != '唐': continue
        if k not in where:
            s = SE[k]
            k2 = min(where, key=lambda x: math.hypot(SE[x]['lon'] - s['lon'], SE[x]['lat'] - s['lat']))
            v = where[k2]
        else:
            v = where[k]
        out.setdefault(v, []).append(k)
    return out


def ts755(keep=()):
    """755 年各点照唐宋卷 755 年节点；keep 里的单位照本卷（唐宋卷在那里留白：天竺、迦湿弥罗、堕罗钵底）"""
    own, drop, now = {}, [], replay()
    for u, ks in TS755.items():
        if u is None:
            drop += [k for k in ks if now.get(k) not in keep]
        else:
            own.setdefault(TS_UNIT.get(u, u), []).extend(ks)
    return own, drop


